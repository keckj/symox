def _namespace():
    ns = {}
    exec("from symox import *", ns)
    exec("from symox.polys.domains import ZZ, QQ, RR, CC, EX, EXRAW, ZZ_I, QQ_I", ns)
    exec("from symox.polys.constructor import construct_domain", ns)
    exec("import mpmath; from symox.abc import x, y, z", ns)
    exec("from fractions import Fraction", ns)
    return ns


NS = _namespace()


def _outcome(case):
    try:
        return 'OK ' + repr(eval(case, NS))
    except Exception as e:
        return 'ERR ' + type(e).__name__ + ': ' + str(e)[:150]


def _domain_of(case):
    m = re.match(r'(.*?)\.(convert|from_sympy|convert_from)\(', case)
    if m:
        return eval(m.group(1), NS)
    return eval(re.match(r'^([A-Za-z_]+(\[[^\]]*\])?)\(', case).group(1), NS)


def _canonical(case):
    r = eval(case, NS)
    if case.startswith('construct_domain'):
        K, e = r
        if isinstance(e, dict):
            e = sorted((str(k), str(K.to_sympy(v))) for k, v in e.items())
        elif isinstance(e, list):
            e = [str(K.to_sympy(v)) for v in e]
        else:
            e = str(K.to_sympy(e))
        return [str(K), e]
    K = _domain_of(case)
    return [str(K), str(K.to_sympy(r))]

