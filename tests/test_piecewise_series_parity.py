@pytest.mark.parametrize("call,expected", CASES)
def test_matches_sympy(call, expected):
    value = eval(call)
    assert str(value) == expected


def test_left_limit_takes_the_left_branch():
    # SymPy 1.14 gives 1 (the right branch); the left branch tends to 0
    assert limit(P2 + x, x, 0, "-") == 0
    assert limit(P2, x, 0, "-") == 0
    assert limit(P2 + x, x, 0, "+") == 1


def test_nseries_of_a_product_uses_leading_branch():
    assert str((P2*x).nseries(x, 0, 4)) == "x + O(x**4)"
