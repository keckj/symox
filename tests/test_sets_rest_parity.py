def _show(r):
    if isinstance(r, (bool, type(None))):
        return repr(r)
    return srepr(r)


@pytest.mark.parametrize("expression,expected", CASES)
def test_reference_srepr(expression, expected):
    assert _show(eval(expression)) == expected


def test_imageset_callable_and_symbol_forms():
    assert imageset(lambda t: t**2, Interval(0, 3)) == Interval(0, 9)
    assert imageset(x, 2*x, Interval(0, 1)) == Interval(0, 2)


def test_tan_image_is_evaluated():
    # Intentional correction: SymPy 1.14 keeps the image set because its
    # solveset leaves tan(x)**2 + 1 = 0 as a ConditionSet; the equation has
    # no solution, and tan is increasing on [0, 1].
    assert imageset(Lambda(x, tan(x)), Interval(0, 1)) == Interval(0, tan(1))
