def namespace(mod):
    ns = {name: getattr(mod, name) for name in dir(mod) if not name.startswith("_")}
    x, y, z, n, k, m, a, b, nu = mod.symbols("x y z n k m a b nu")
    ns.update(x=x, y=y, z=z, n=n, k=k, m=m, a=a, b=b, nu=nu)
    ns["p"] = mod.Symbol("p", positive=True)
    ns["i"] = mod.Symbol("i", integer=True)
    ns["j"] = mod.Symbol("j", integer=True, nonnegative=True)
    if mod is sympy:
        from sympy.functions.combinatorial.numbers import stirling
        ns["stirling"] = stirling
    return ns


def numeric_equal(a, b, syms, trials=4):
    rnd = random.Random(1234)
    a_f = sympy.lambdify(syms, a, modules=["mpmath"])
    b_f = sympy.lambdify(syms, b, modules=["mpmath"])
    for _ in range(trials):
        pt = [complex(rnd.uniform(0.2, 0.9), rnd.uniform(-0.2, 0.2)) for _ in syms]
        try:
            va = complex(a_f(*pt))
            vb = complex(b_f(*pt))
        except (ZeroDivisionError, OverflowError, ValueError, TypeError, NameError, AttributeError):
            return None
        if cmath.isnan(va) and cmath.isnan(vb):
            continue
        if abs(va - vb) > 1e-8 * max(1.0, abs(va), abs(vb)):
            return False
    return True


def floats_close(s_x, s_s):
    try:
        a = complex(sympy.sympify(s_x))
        b = complex(sympy.sympify(s_s))
    except (TypeError, ValueError, sympy.SympifyError):
        return False
    return abs(a - b) <= 1e-13 * max(abs(b), 1e-300)


def compare(case, ns_s, ns_x):
    exp_s = eval(case, ns_s)
    try:
        exp_x = eval(case, ns_x)
    except Exception as e:  # noqa: BLE001
        return "error", f"{type(e).__name__}: {e}", str(exp_s)
    s_s, s_x = str(exp_s), str(exp_x)
    if s_s == s_x:
        return "same", s_x, s_s
    if floats_close(s_x, s_s):
        return "float-ulp", s_x, s_s
    try:
        back = sympy.sympify(s_x, locals={"Li": sympy.Li, "E1": sympy.E1})
    except Exception:  # noqa: BLE001
        return "unparseable", s_x, s_s
    if isinstance(exp_s, sympy.Basic) and isinstance(back, sympy.Basic):
        if back == exp_s:
            return "same-tree", s_x, s_s
        try:
            if sympy.simplify(back - exp_s) == 0:
                return "equivalent", s_x, s_s
        except Exception:  # noqa: BLE001
            pass
        syms = sorted(exp_s.free_symbols | back.free_symbols, key=str)
        if syms and not exp_s.has(sympy.Derivative):
            try:
                r = numeric_equal(back, exp_s, syms)
                if r:
                    return "equivalent", s_x, s_s
            except Exception:  # noqa: BLE001
                pass
    return "DIFFERENT", s_x, s_s


def extra_checks():
    """Non expression API: stirling numbers, multinomial coefficients."""
    from sympy.functions.combinatorial.numbers import stirling as s_stirling

    bad = []
    for args, kw in [((5, 2), {}), ((5, 2), {"kind": 1}), ((5, 2), {"kind": 1, "signed": True}),
                     ((10, 3), {}), ((0, 0), {}), ((5, 2), {"d": 2}), ((12, 4), {"kind": 1}),
                     ((9, 5), {"kind": 1, "signed": True}), ((3, 5), {})]:
        want = s_stirling(*args, **kw)
        got = symox.stirling(*args, **kw)
        if str(want) != str(got):
            bad.append((f"stirling{args}{kw}", str(got), str(want)))
    for m, n in [(2, 3), (3, 2), (4, 4), (1, 5)]:
        want = {k: int(v) for k, v in sympy.multinomial_coefficients(m, n).items()}
        got = {tuple(k): int(v) for k, v in symox.multinomial_coefficients(m, n).items()}
        if want != got:
            bad.append((f"multinomial_coefficients({m}, {n})", str(got), str(want)))
    return bad


def run(verbose=True):
    stats = {}
    bad = []
    ns_s = namespace(sympy)
    ns_x = namespace(symox)
    for case in CASES:
        status, got, want = compare(case, ns_s, ns_x)
        stats[status] = stats.get(status, 0) + 1
        if status not in ("same", "same-tree"):
            if verbose:
                print(f"[{status:11s}] {case:45s} symox: {got:40s} sympy: {want}")
            if status in ("DIFFERENT", "error", "unparseable") and case not in KNOWN_DEVIATIONS:
                bad.append((case, got, want))
    extra = extra_checks()
    for c, g, w in extra:
        if verbose:
            print(f"[DIFFERENT  ] {c:45s} symox: {g:40s} sympy: {w}")
    bad.extend(extra)
    if verbose:
        print("\nsummary:", stats, f"(total {len(CASES)}), extra checks failed: {len(extra)}")
    return bad


def test_special_against_sympy():
    bad = run(verbose=False)
    assert not bad, "\n".join(f"{c}: symox={g} sympy={w}" for c, g, w in bad)


if __name__ == "__main__":
    sys.exit(1 if run() else 0)
