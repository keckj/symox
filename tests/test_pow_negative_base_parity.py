def test_dsolve_third_order_constant_coefficients():
    f = Function('f')
    for _ in range(3):
        solution = dsolve(f(x).diff(x) + sqrt(2)*f(x).diff(x, 3), f(x))
        assert str(solution.rhs) == 'C1 + C2*sin(2**(3/4)*x/2) + C3*cos(2**(3/4)*x/2)'
