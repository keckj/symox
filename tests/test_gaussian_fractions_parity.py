import pytest
import symox as S
from symox.polys.constructor import construct_domain


def namespace():
    g = {k: getattr(S, k) for k in dir(S) if not k.startswith('_')}
    d = S.polys.domains
    g.update({k: getattr(d, k) for k in ['ZZ', 'QQ', 'ZZ_I', 'QQ_I', 'EX']})
    g['construct_domain'] = construct_domain
    exec("x, y, z, n, N = symbols('x y z n N')", g)
    exec("K = ZZ_I.frac_field(y); L = QQ_I.frac_field(y); "
         "M = ZZ_I.frac_field(N, pi); R = ZZ_I[y]; Q = QQ_I[y]", g)
    return g


def outcome(case):
    try:
        r = eval(case, namespace())
    except Exception as e:
        return 'EXC ' + type(e).__name__ + ': ' + str(e)[:150]
    out = str(r)
    return out if out == repr(r) else out + ' ||| ' + repr(r)


