def _outcome(code):
    try:
        return str(_eval(code))
    except Exception as e:
        return 'E:' + type(e).__name__ + ': ' + str(e)[:60]


@pytest.mark.parametrize('code, expected', SIMPLIFICATION_CASES)
def test_simplification_matches_reference(code, expected):
    got = _outcome(code)
    if expected.startswith('E:'):
        assert got.split(':')[1] == expected.split(':')[1]
    else:
        assert got == expected


