# --- deliberate differences (docs/algorithmic-parity.md) ---------------------

def test_commutative_unknowns_take_commutative_values():
    # Coefficient equations of the free algebra decide more than the
    # reference, which raises PolynomialError for these equations.
    assert sp.solve(x**2*A - A, x) == [-1, 1]
    assert sp.solve(x**2 - 1 + A, x) == []
    assert sp.solve(exp(x)*A - A, x) == [0]


def test_noncommutative_unknown_keeps_factor_order():
    assert sp.solve(B*A - C, B) == [C*A**-1]
    assert sp.solve(A*B*C - 1, B) == [(C*A)**-1]
    assert sp.solve(A*B - B, B) == [0]
    assert sp.solve(A*B + B, A) == [-1]
    with pytest.raises(NotImplementedError):
        sp.solve(A*B - B*A, A)
    with pytest.raises(NotImplementedError):
        sp.solve([A - B, x - 1], [A, x])


def test_unsupported_operations_raise_instead_of_commuting():
    with pytest.raises(NotImplementedError):
        sp.adjoint(A*B)
    with pytest.raises(NotImplementedError):
        sp.transpose(A*B)
    with pytest.raises(PolynomialError):
        sp.linsolve([A*x - B], x)
    with pytest.raises(PolynomialError):
        sp.Poly(A*B + B*A)
    assert sp.transpose(x*y) == x*y


def test_equals_is_undecided_for_a_nonzero_difference():
    assert (A*B).equals(B*A) is None
    assert (A*B).equals(A*B) is True
    assert (A*(B + C)).equals(A*B + A*C) is True


def test_linear_mask_never_commutes():
    assert sp.simplify(sin(x)**2*A*B + cos(x)**2*A*B) == A*B
    assert sp.trigsimp(sin(x)**2*A + cos(x)**2*A) == A
    assert sp.radsimp(A/(1 + sqrt(2))) == (-1 + sqrt(2))*A


def test_commutative_inputs_keep_native_results():
    assert sp.cancel((x**2 - 1)/(x - 1)) == x + 1
    assert sp.factor(x**2 - 1) == (x - 1)*(x + 1)
    assert sp.together(1/x + 1/y) == (x + y)/(x*y)
    assert sp.expand(exp(x + y)) == exp(x)*exp(y)
    assert sp.solve(x**2 - 1, x) == [-1, 1]
