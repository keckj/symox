@pytest.mark.parametrize('code, kind, expected', CORE_CASES)
def test_core_matches_reference(code, kind, expected):
    if kind == 'E':
        with pytest.raises(Exception) as info:
            _eval(code)
        assert type(info.value).__name__ == expected
        return
    value = _eval(code)
    if kind == 'str':
        assert str(value) == expected
    elif kind == 'srepr':
        assert srepr(value) == expected
    elif kind == 'S':
        assert value == expected
    else:
        assert repr(value) == expected


