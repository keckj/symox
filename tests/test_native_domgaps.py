def test_smith_gaussian_zero_pivot_keeps_reference_error():
    # SymPy 1.14: the QQ_I zero compares != 0, so 1 / 0 is attempted.
    m = DomainMatrix([[QQ_I(1), QQ_I(2)], [QQ_I(2), QQ_I(4)]], (2, 2), QQ_I)
    with pytest.raises(ZeroDivisionError):
        smith_normal_form(m)
