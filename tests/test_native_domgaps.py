def _sym(rows):
    return [[sympify(v) for v in row] for row in rows]


@pytest.mark.parametrize('rows, snf, inv, s, t', SMITH_FX)
def test_smith_fraction_field_rank_deficient(rows, snf, inv, s, t):
    K = QQ.frac_field(x)
    m = _fx(rows, K)
    S = smith_normal_form(m)
    assert S.domain == K and _values(S) == _sym(snf)
    factors = invariant_factors(m)
    assert tuple(K.to_sympy(f) for f in factors) == tuple(sympify(v) for v in inv)
    S2, s2, t2 = smith_normal_decomp(m)
    # SymPy keeps different internal formats here, so compare by value.
    assert _values(S2) == _sym(snf)
    assert _values(s2) == _sym(s) and _values(t2) == _sym(t)
    assert _values(s2 * m * t2) == _sym(snf)


