@pytest.mark.parametrize('K', [QQ.frac_field(x), QQ[x], ZZ[x], ZZ.frac_field(x)])
def test_bool_and_large_int_operands(K):
    # SymPy 1.14: the constant coefficient is compared with the Python int.
    assert (K.one == True, True == K.one, K.one == False, K.zero == False) == (True, True, False, True)
    big = 10**30
    assert K.from_sympy(sympify(big)) == big and big == K.from_sympy(sympify(big))
    assert K.from_sympy(sympify(2)) != big
