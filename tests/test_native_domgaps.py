def _code(f):
    try:
        return 'T' if f() else 'F'
    except TypeError:
        return 'E'


def _elements(K):
    out = []
    for text in ELEMENTS:
        try:
            out.append((text, K.from_sympy(sympify(text))))
        except Exception:
            pass
    return out


@pytest.mark.parametrize('name', sorted(EXPECTED))
def test_element_comparisons_match_reference(name):
    K = DOMAINS[name]()
    elements = _elements(K)
    assert sorted(t for t, _ in elements) == sorted(EXPECTED[name])
    namespace = {'Integer': Integer, 'Rational': Rational, 'QQ': QQ, 'ZZ': ZZ, 'x': x}
    others = [eval(text, namespace) for text in OTHERS]
    for text, e in elements:
        got = ''.join(_code(lambda: e == o) + _code(lambda: e != o) + _code(lambda: o == e)
                      + _code(lambda: o != e) for o in others)
        if '|' in EXPECTED[name][text]:
            got += '|' + ''.join(_code(lambda: f(e, e2)) for _, e2 in elements
                                 for f in (operator.lt, operator.le, operator.gt, operator.ge))
        assert got == EXPECTED[name][text], (name, text)


def _fx(rows, K):
    return DomainMatrix([[K.from_sympy(sympify(v)) for v in row] for row in rows],
                        (len(rows), len(rows[0]) if rows else 0), K)


def _values(m):
    return [[m.domain.to_sympy(v) for v in row] for row in m.to_list()]


