def test_sieve_state_and_repr():
    s1, s2 = sp.Sieve(), sx.Sieve()
    for s in (s1, s2):
        s.extend(100)
        list(s.totientrange(1, 30))
        list(s.mobiusrange(1, 40))
    assert repr(s1) == repr(s2)
    assert list(s1._list) == list(s2._list)
    s1._reset(prime=True)
    s2._reset(prime=True)
    assert repr(s1) == repr(s2)


def test_factor_cache_and_randprime():
    c = sx.ntheory.factor_cache
    assert 'maxsize' in repr(c) or isinstance(repr(c), str)
    for a, b in [(10, 20), (1000, 2000), (2, 3)]:
        p = sx.randprime(a, b)
        assert type(p) is int and a <= p < b and sp.isprime(p)
    assert sx.randprime(20, 10) is None
    with pytest.raises(ValueError):
        sx.randprime(24, 28)


def test_top_level_exports_match_sympy():
    for name in ('igcd', 'ilcm', 'integer_log', 'num_digits', 'trailing',
                 'mod_inverse', 'integer_nthroot', 'continued_fraction',
                 'Sieve', 'kronecker_symbol', 'npartitions', 'factorrat',
                 'egyptian_fraction', 'discrete_log', 'convolution', 'fft'):
        assert hasattr(sx, name), name
    for name in sp.ntheory.__all__:
        assert hasattr(sx.ntheory, name), name
    for name in sp.discrete.__all__:
        assert hasattr(sx.discrete, name), name


def test_results_pickle():
    for v in (sx.continued_fraction(sx.sqrt(7)), sx.egyptian_fraction(
            sx.Rational(5, 7)), sx.factorrat(sx.Rational(8, 9))):
        assert pickle.loads(pickle.dumps(v)) == v
    assert run('symox', 'divisor_count(24)') == run('sympy', 'divisor_count(24)')
