def test_factor_is_reproducible():
    # The reference equal-degree factorization is randomized; symox seeds it.
    results = set()
    for _ in range(5):
        try:
            results.add(str(factor_list(x**2 - 1, modulus=9)))
        except NotInvertible:
            results.add('NotInvertible')
    assert len(results) == 1


