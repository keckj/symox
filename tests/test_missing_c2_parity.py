@pytest.mark.parametrize('name, code, expected', CASES, ids=[c[0] for c in CASES])
def test_matches_reference(name, code, expected):
    namespace = {}
    exec('from symox import *', namespace)
    buffer = io.StringIO()
    with contextlib.redirect_stdout(buffer):
        exec(code, namespace)
    result = str(namespace['r'])
    if buffer.getvalue():
        result += ' |stdout: ' + buffer.getvalue().strip()
    assert result == expected
