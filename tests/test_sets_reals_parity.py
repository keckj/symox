def _show(r):
    if isinstance(r, (bool, type(None), dict)):
        return repr(r)
    if isinstance(r, (list, tuple)):
        return '[' + ', '.join(srepr(t) if not isinstance(t, (bool, type(None), tuple)) else repr(t) for t in r) + ']'
    return srepr(r)


@pytest.mark.parametrize("expression,expected", CASES)
def test_reference_srepr(expression, expected):
    assert _show(eval(expression)) == expected
