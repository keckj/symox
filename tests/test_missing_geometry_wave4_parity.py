def _run(code):
    namespace = {}
    exec('from symox import *', namespace)
    exec('from symox.geometry import *', namespace)
    exec('from symox.abc import t, x, y, z, k', namespace)
    parts = code.split('; ')
    try:
        for part in parts[:-1]:
            exec(part, namespace)
        return str(eval(parts[-1], namespace))
    except Exception as exc:
        return 'EXC ' + type(exc).__name__


