def test_reference_output(code, expected):
    assert _run(code) == expected


def test_curve_reflect_is_the_mathematical_image():
    # Intentional divergence: SymPy 1.14 returns the curve unchanged.
    s = Symbol('s')
    curve = Curve([2*s, s**2], (s, 0, 2))
    assert str(curve.reflect(Line((0, 0), (1, 1)))) == 'Curve((s**2, 2*s), (s, 0, 2))'


def test_nonconvex_bisectors_equal_reference_values():
    p = Polygon(Point(0, 0), Point(2, 0), Point(1, 1), Point(0, 3))
    result = p.bisectors()
    assert list(result) == [Point(0, 3), Point(0, 0), Point(2, 0), Point(1, 1)]
    expected = {Point(0, 3): (0.229752920547361, 2.02675101053227),
                Point(0, 0): (0.707106781186548, 0.707106781186548),
                Point(2, 0): (1.07612046748871, 0.38268343236509),
                Point(1, 1): (0.188757814824439, 0.415289715336235)}
    for vertex, (ex, ey) in expected.items():
        ray = result[vertex]
        assert ray.p1 == vertex
        assert abs(float(N(ray.p2.x)) - ex) < 1e-12 and abs(float(N(ray.p2.y)) - ey) < 1e-12


def test_plane_circle_parameter_is_a_valid_representative():
    t = Symbol('t')
    plane = Plane((1, 2, 3), (1, 1, 1))
    point = plane.arbitrary_point(t).subs(t, 5*pi/4)
    value = plane.parameter_value(point, t)[t]
    # SymPy returns 5*pi/4; any 2*pi translate is the same point.
    assert Abs(value - 5*pi/4) in (0, 2*pi)
    assert plane.arbitrary_point(t).subs(t, value).equals(point)


