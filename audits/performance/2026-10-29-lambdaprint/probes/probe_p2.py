import sys
lib = sys.argv[1]
S = __import__(lib)
x, y = S.symbols('x y')
def r(tag, f):
    try: v = f()
    except Exception as e: v = 'ERR %s: %s' % (type(e).__name__, str(e)[:150])
    print(tag, '=', repr(v) if not isinstance(v, str) else v)
r('alias_field', lambda: str(S.QQ.algebraic_field((S.sqrt(2), 'alpha'))))
r('alias_repr', lambda: repr(S.QQ.algebraic_field((S.sqrt(2), 'alpha'))))
r('field_plain', lambda: str(S.QQ.algebraic_field(S.sqrt(2))))
r('dom_type', lambda: type(S.ZZ).__name__ + ' ' + type(S.QQ).__name__ + ' ' + type(S.RR).__name__)
r('poly_dom_type', lambda: type(S.Poly(x**2 + 1, x, domain='QQ<sqrt(2)>').domain).__name__)
r('catalan', lambda: str(S.Catalan.evalf(30)))
r('jn', lambda: str(S.jn(2, 1.5 + 0.5*S.I).evalf()))
r('yn', lambda: str(S.yn(2, 1.5 + 0.5*S.I).evalf()))
r('nsolve_noroot', lambda: S.nsolve(x**2 + 1, x, 1))
r('nsolve_complex', lambda: str(S.nsolve(x**2 + 1, x, 1j)))
r('nsolve_sys', lambda: str(S.nsolve([x**2 + y - 2, x - y], [x, y], [1, 1])))
r('nsolve_bad', lambda: S.nsolve([x**2 + y**2 + 1, x - y], [x, y], [1, 1]))
r('nsolve_prec', lambda: str(S.nsolve(S.cos(x) - x, x, 1, prec=30)))
r('undefpred', lambda: str(S.Predicate('mypred')(x)))
r('undefpred_t', lambda: type(S.Predicate('mypred')).__name__)
r('matrix_multiline', lambda: str(S.Matrix([[x, 1], [2, y]])))
r('dummy_str', lambda: str(S.Dummy('d')))
r('pw_tri', lambda: str(S.Piecewise((0, x < 0), (x, x < 1), (2 - x, x < 2), (0, True))))
