"""Regenerate symox/_sympy_classes.py from an installed reference SymPy.

Run with the reference interpreter, never with the downstream routing facade:

    python -I tools/sympy_class_table.py > python/symox/_sympy_classes.py

The table records each public SymPy class name in the packages that describe
scalar expression nodes, its defining module and its direct SymPy bases.
Native nodes use it to present SymPy's nominal type, module and MRO.
"""
import collections
import importlib
import pkgutil
import sys

import sympy

PACKAGES = ('core', 'functions', 'logic', 'sets', 'series', 'integrals', 'concrete',
            'polys', 'simplify', 'calculus', 'tensor', 'assumptions')


def selected(module):
    parts = (module or '').split('.')
    return (len(parts) > 1 and parts[0] == 'sympy' and parts[1] in PACKAGES
            and '.tests' not in module and 'benchmarks' not in module)


def main():
    for info in pkgutil.walk_packages(sympy.__path__, 'sympy.'):
        if selected(info.name):
            try:
                importlib.import_module(info.name)
            except Exception:
                pass
    seen = [sympy.Basic]
    def walk(cls):
        for sub in cls.__subclasses__():
            if sub not in seen:
                seen.append(sub)
                walk(sub)
    walk(sympy.Basic)
    by_name = collections.defaultdict(list)
    for cls in seen:
        if selected(cls.__module__) and cls.__qualname__ == cls.__name__:
            by_name[cls.__name__].append(cls)
    def rank(cls):
        return PACKAGES.index(cls.__module__.split('.')[1]), len(cls.__module__)
    chosen = {name: min(classes, key=rank) for name, classes in by_name.items()}
    needed = {base for cls in chosen.values() for base in cls.__mro__
              if (base.__module__ or '').startswith('sympy.')}
    names = collections.Counter(cls.__name__ for cls in needed)
    duplicates = [name for name, count in names.items() if count > 1]
    if duplicates:
        raise SystemExit('ambiguous class names: '+', '.join(sorted(duplicates)))
    print('"""SymPy %s class names, modules and direct bases for native nodes.' % sympy.__version__)
    print()
    print('Generated by tools/sympy_class_table.py from the reference SymPy. Do not edit.')
    print('"""')
    print()
    print('CLASSES = {')
    for cls in sorted(needed, key=lambda cls: cls.__name__):
        bases = tuple(base.__name__ for base in cls.__bases__ if base in needed)
        print(f'    {cls.__name__!r}: ({cls.__module__!r}, {bases!r}),')
    print('}')


if __name__ == '__main__':
    sys.exit(main())
