class DataType:
    def __init__(self,cname,fname,pyname,jlname,octname,rsname):
        self.cname,self.fname,self.pyname,self.jlname,self.octname,self.rsname=cname,fname,pyname,jlname,octname,rsname
    def get(self,language):return getattr(self,{'C':'cname','C89':'cname','C99':'cname','F95':'fname','FORTRAN':'fname','PYTHON':'pyname','JULIA':'jlname','OCTAVE':'octname','RUST':'rsname'}[language.upper()])
default_datatypes={'int':DataType('int','integer','int','Int32','int32','i32'),
 'float':DataType('double','real(kind=8)','float','Float64','double','f64'),
 'complex':DataType('double complex','complex(kind=8)','complex','ComplexF64','double','num_complex::Complex64')}

def get_default_datatype(expr,complex_allowed=None):
    value=expr if hasattr(expr,'is_integer') else S.sympify(expr)
    if value.is_integer is True:return default_datatypes['int']
    if complex_allowed and value.is_real is False:return default_datatypes['complex']
    return default_datatypes['float']


class Argument:
    def __init__(self,name,datatype=None,dimensions=None,precision=None):
        self.name=S.Symbol(name) if isinstance(name,str) else name
        self.datatype=datatype or get_default_datatype(self.name);self.dimensions=dimensions;self.precision=precision
    def get_datatype(self,language):return self.datatype.get(language)
class InputArgument(Argument):pass
class OutputArgument(Argument):
    def __init__(self,name,result_var,expr,datatype=None,dimensions=None,precision=None):
        super().__init__(name,datatype,dimensions,precision);self.result_var=result_var;self.expr=expr
class InOutArgument(OutputArgument):pass
class Result(Argument):
    def __init__(self,expr,name=None,result_var=None,datatype=None,dimensions=None,precision=None):
        expr=S.sympify(expr) if not hasattr(expr,'shape') else expr
        name=name or S.Symbol('result');super().__init__(name,datatype or get_default_datatype(expr),dimensions,precision)
        self.expr=expr;self.result_var=result_var or self.name
class Routine:
    def __init__(self,name,arguments,results,local_vars,global_vars):
        if not str(name).isidentifier():raise ValueError('routine name must be an identifier')
        self.name=str(name);self.arguments=list(arguments);self.results=list(results);self.local_vars=set(local_vars);self.global_vars=set(global_vars)
    @property
    def variables(self):return {a.name for a in self.arguments}|self.local_vars|self.global_vars
    @property
    def result_variables(self):return [a for a in self.arguments if isinstance(a,OutputArgument)]+self.results


def make_routine(name,expr,argument_sequence=None,global_vars=None,language='F95'):
    expressions=list(expr) if isinstance(expr,(list,tuple)) else [expr];globals_=set(global_vars or ())
    inputs=set();outputs=[];results=[]
    for i,value in enumerate(expressions):
        if getattr(value,'class_name',None)=='Equality':
            lhs,rhs=value.lhs,value.rhs;inputs.update(rhs.free_symbols);outputs.append(OutputArgument(lhs,lhs,rhs))
        elif hasattr(value,'shape'):
            symbol=S.Symbol(str(name)+'_out'+str(i));dims=tuple((S.Integer(0),S.Integer(n)-1) for n in value.shape)
            outputs.append(OutputArgument(symbol,symbol,value,default_datatypes['float'],dims));inputs.update(value.free_symbols)
        else:
            value=S.sympify(value);inputs.update(value.free_symbols);results.append(Result(value,str(name)+'_result'+str(i)))
    output_names={o.name for o in outputs};arguments=[]
    for symbol in sorted(inputs-globals_-output_names,key=str):arguments.append(InputArgument(symbol))
    for output in outputs:
        if output.name in inputs:output=InOutArgument(output.name,output.result_var,output.expr,output.datatype,output.dimensions)
        arguments.append(output)
    if argument_sequence is not None:
        lookup={a.name:a for a in arguments};sequence=list(argument_sequence)
        missing=set(lookup)-set(sequence)
        if missing:raise ValueError('argument_sequence omits '+', '.join(map(str,missing)))
        arguments=[lookup.get(s,InputArgument(s)) for s in sequence]
    return Routine(name,arguments,results,set(),globals_)


class CodeGen:
    language='C';extension='c'
    def __init__(self,project='project',cse=False):self.project=project;self.cse=cse
    def routine(self,name,expr,argument_sequence=None,global_vars=None):return make_routine(name,expr,argument_sequence,global_vars,self.language)
    def _source(self,routine):raise NotImplementedError('select a language CodeGen subclass')
    def write(self,routines,prefix,to_files=False,header=True,empty=True):
        source='\n\n'.join(self._source(r) for r in routines)
        if header:source='/* Generated by symox: '+str(self.project)+' */\n'+source if self.language=='C' else source
        files=[(str(prefix)+'.'+self.extension,source+'\n')]
        if self.language=='C':
            source='#include <math.h>\n#include <stdbool.h>\n#include <stdint.h>\n#include <stdio.h>\n#include <stdlib.h>\n'+source
            files[0]=(files[0][0],source+'\n')
            files.append((str(prefix)+'.h','\n'.join(self._prototype(r)+';' for r in routines)+'\n'))
        if to_files:
            for name,text in files:Path(name).parent.mkdir(parents=True,exist_ok=True);Path(name).write_text(text)
            return None
        return files


class CCodeGen(CodeGen):
    def __init__(self,project='project',printer=None,preprocessor_statements=None,cse=False):
        super().__init__(project,cse)
        from ..printing.c import C99CodePrinter
        self.printer=printer or C99CodePrinter();self.preprocessor_statements=list(preprocessor_statements or [])
    def _prototype(self,routine):
        if len(routine.results)>1:raise ValueError('C routines can return one scalar; use output equations for multiple results')
        result=routine.results[0].datatype.cname if routine.results else 'void'
        args=[]
        for arg in routine.arguments:
            args.append(arg.datatype.cname+(' *' if isinstance(arg,OutputArgument) or arg.dimensions else ' ')+str(arg.name))
        return result+' '+routine.name+'('+(', '.join(args) or 'void')+')'
    def _source(self,routine):
        from ..printing._nodes import indent
        body=[]
        for output in routine.arguments:
            if not isinstance(output,OutputArgument):continue
            if hasattr(output.expr,'shape'):
                for i,value in enumerate(output.expr):body.append(str(output.name)+'['+str(i)+'] = '+self.printer.doprint(value)+';')
            else:body.append('*'+str(output.name)+' = '+self.printer.doprint(output.expr)+';')
        for result in routine.results:body.append('return '+self.printer.doprint(result.expr)+';')
        return '\n'.join(self.preprocessor_statements)+('\n' if self.preprocessor_statements else '')+self._prototype(routine)+' {\n'+indent('\n'.join(body))+'\n}'


class FCodeGen(CodeGen):
    language='F95';extension='f90'
    def __init__(self,project='project',printer=None):
        super().__init__(project)
        from ..printing.fortran import FCodePrinter
        self.printer=printer or FCodePrinter()
    def _source(self,routine):
        from ..printing._nodes import indent
        args=', '.join(str(a.name) for a in routine.arguments);function=bool(routine.results)
        if len(routine.results)>1:raise ValueError('Fortran functions require one scalar result')
        head=(routine.results[0].datatype.fname+' function ' if function else 'subroutine ')+routine.name+'('+args+')'
        declarations=['implicit none']
        for arg in routine.arguments:
            intent='inout' if isinstance(arg,InOutArgument) else 'out' if isinstance(arg,OutputArgument) else 'in'
            dims=''
            if arg.dimensions:dims=', dimension('+', '.join(str(hi-lo+1) for lo,hi in arg.dimensions)+')'
            declarations.append(arg.datatype.fname+', intent('+intent+')'+dims+' :: '+str(arg.name))
        body=[]
        for arg in routine.arguments:
            if isinstance(arg,OutputArgument):
                if hasattr(arg.expr,'shape'):
                    for i in range(arg.expr.rows):
                        for j in range(arg.expr.cols):body.append(str(arg.name)+'('+str(i+1)+','+str(j+1)+') = '+self.printer.doprint(arg.expr[i,j]))
                else:body.append(str(arg.name)+' = '+self.printer.doprint(arg.expr))
        if function:body.append(routine.name+' = '+self.printer.doprint(routine.results[0].expr))
        return head+'\n'+indent('\n'.join(declarations+body))+'\nend '+('function ' if function else 'subroutine ')+routine.name


class _ScriptCodeGen(CodeGen):
    def __init__(self,project='project',printer=None):super().__init__(project);self.printer=printer
    def _expression(self,expr):
        return self.printer.doprint(expr) if self.printer is not None else getattr(S,{'Julia':'julia_code','Octave':'octave_code','Rust':'rust_code'}[self.language])(expr)
    def _source(self,routine):
        inputs=[a for a in routine.arguments if not isinstance(a,OutputArgument)];outputs=[a for a in routine.arguments if isinstance(a,OutputArgument)]
        resultvars=[str(a.name) for a in outputs]+[str(r.name) for r in routine.results]
        assignments=[str(a.name)+' = '+self._expression(a.expr) for a in outputs]+[str(r.name)+' = '+self._expression(r.expr) for r in routine.results]
        if self.language=='Julia':return 'function '+routine.name+'('+', '.join(str(a.name) for a in inputs)+')\n'+'\n'.join('    '+line for line in assignments)+'\n    return '+', '.join(resultvars)+'\nend'
        if self.language=='Octave':return 'function ['+', '.join(resultvars)+'] = '+routine.name+'('+', '.join(str(a.name) for a in inputs)+')\n'+'\n'.join('    '+line+';' for line in assignments)+'\nend'
        if outputs or len(routine.results)!=1:raise ValueError('Rust codegen requires one scalar result')
        r=routine.results[0]
        return 'pub fn '+routine.name+'('+', '.join(str(a.name)+': '+a.datatype.rsname for a in inputs)+') -> '+r.datatype.rsname+' {\n    '+self._expression(r.expr)+'\n}'
class JuliaCodeGen(_ScriptCodeGen):language='Julia';extension='jl'
class OctaveCodeGen(_ScriptCodeGen):language='Octave';extension='m'
class RustCodeGen(_ScriptCodeGen):
    language='Rust';extension='rs'
    def _expression(self,expr):
        if self.printer is not None:return self.printer.doprint(expr)
        from ..printing.rust import RustCodePrinter
        return RustCodePrinter().doprint(expr)


def codegen(name_expr,language=None,prefix=None,project='project',to_files=False,header=True,empty=True,
            argument_sequence=None,global_vars=None,standard=None,code_gen=None,printer=None):
    pairs=[name_expr] if isinstance(name_expr,tuple) and len(name_expr)==2 and isinstance(name_expr[0],str) else list(name_expr)
    language=(language or 'C').upper()
    classes={'C':CCodeGen,'C89':CCodeGen,'C99':CCodeGen,'C11':CCodeGen,'F95':FCodeGen,'FORTRAN':FCodeGen,'F90':FCodeGen,'JULIA':JuliaCodeGen,'OCTAVE':OctaveCodeGen,'RUST':RustCodeGen}
    if code_gen is None:
        if language not in classes:raise ValueError('unsupported code generation language '+language)
        code_gen=classes[language](project,printer=printer)
    routines=[code_gen.routine(name,expr,argument_sequence,global_vars) for name,expr in pairs]
    return code_gen.write(routines,prefix or pairs[0][0],to_files,header,empty)
