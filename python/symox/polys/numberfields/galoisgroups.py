"""Exact Galois groups of irreducible rational polynomials of degree <= 6.

Cubic groups are determined by their discriminant. Quartics use the cubic
resolvent and, when needed, factorization over the discriminant quadratic
field. Quintics and sextics port SymPy's resolvent-coefficient lookup
(Cohen, Alg. 6.3.9 and 6.3.10) with deterministic Tschirnhausen
transformations; every decision is made on exact integer resolvents.
"""
from collections import defaultdict
import operator
import random


class GaloisGroupException(Exception):
    ...


class ResolventException(GaloisGroupException):
    ...


class MaxTriesException(GaloisGroupException):
    ...


def _dup_poly(coeffs, gen):
    from ... import Poly, ZZ
    return Poly([int(c) for c in coeffs], gen, domain=ZZ)


def tschirnhausen_transformation(T, max_coeff=10, max_tries=30, history=None,
                                 fixed_order=True):
    """Find another monic irreducible integer polynomial defining the same
    number field as *T* (Cohen, Alg. 6.3.4); returns the pair ``(A, U)``."""
    from ... import Poly, Dummy, ZZ
    from .utilities import coeff_search
    X = Dummy('X')
    n = T.degree()
    if history is None:
        history = set()
    history.add(tuple(T.all_coeffs()))
    coeff_generators = {}
    deg_coeff_sum = 3
    current_degree = 2

    def get_coeff_generator(degree):
        gen = coeff_generators.get(degree, coeff_search(degree, 1))
        coeff_generators[degree] = gen
        return gen

    for i in range(max_tries):
        if fixed_order:
            gen = get_coeff_generator(current_degree)
            coeffs = next(gen)
            m = max(abs(c) for c in coeffs)
            if current_degree + m > deg_coeff_sum:
                if current_degree == 2:
                    deg_coeff_sum += 1
                    current_degree = deg_coeff_sum - 1
                else:
                    current_degree -= 1
                gen = get_coeff_generator(current_degree)
                coeffs = next(gen)
            a = [1] + [int(c) for c in coeffs]
        else:
            C = min(i//5 + 1, max_coeff)
            d = random.randint(2, n - 1)
            a = [random.randint(-C, C) for _ in range(d + 1)]
            a[0] = a[0] or 1
        A = Poly(a, T.gen, domain=ZZ)
        U = Poly(T.resultant(X - A.as_expr()), X, domain=ZZ)
        if tuple(U.all_coeffs()) not in history and U.is_sqf:
            return A, U
    raise MaxTriesException


def has_square_disc(T):
    """Whether the Poly *T* has a square discriminant."""
    from ...ntheory.primetest import is_square
    return is_square(int(T.discriminant()))


def get_resolvent_by_lookup(T, number):
    """Resolvent of *T* (a Poly) from SymPy's coefficient lookup table."""
    from .resolvent_lookup import resolvent_coeff_lambdas
    L = resolvent_coeff_lambdas[(int(T.degree()), number)]
    T_coeffs = [int(c) for c in T.all_coeffs()[1:]]
    return _dup_poly([1] + [c(*T_coeffs) for c in L], T.gen)


def _galois_group_degree_5_lookup_ext_factor(T, max_tries=30, randomize=False):
    from ... import Poly, QQ
    from ...combinatorics.galois import S5TransitiveSubgroups
    _T = T
    history = set()
    for i in range(max_tries):
        R = get_resolvent_by_lookup(T, 1)
        if R.is_sqf:
            break
        _, T = tschirnhausen_transformation(T, max_tries=max_tries,
                                            history=history,
                                            fixed_order=not randomize)
    else:
        raise MaxTriesException
    sq_disc = has_square_disc(T)
    if R.is_irreducible:
        return ((S5TransitiveSubgroups.A5, True) if sq_disc
                else (S5TransitiveSubgroups.S5, False))
    if not sq_disc:
        return (S5TransitiveSubgroups.M20, False)
    # Gal(T) is D5 or C5; it has order 5 iff T splits completely over the
    # field generated by one of its roots.
    fl = Poly(_T.as_expr(), _T.gen,
              domain=QQ.alg_field_from_poly(_T)).factor_list()[1]
    if len(fl) == 5:
        return (S5TransitiveSubgroups.C5, True)
    return (S5TransitiveSubgroups.D5, True)


def _galois_group_degree_6_lookup(T, max_tries=30, randomize=False):
    from ...combinatorics.galois import S6TransitiveSubgroups
    history = set()
    for i in range(max_tries):
        R = get_resolvent_by_lookup(T, 1)
        if R.is_sqf:
            break
        _, T = tschirnhausen_transformation(T, max_tries=max_tries,
                                            history=history,
                                            fixed_order=not randomize)
    else:
        raise MaxTriesException
    factors_by_deg = defaultdict(list)
    for r, _ in R.factor_list()[1]:
        factors_by_deg[int(r.degree())].append(r)
    L = sorted(sum([[d] * len(ff) for d, ff in factors_by_deg.items()], []))
    T_has_sq_disc = has_square_disc(T)
    if L == [1, 2, 3]:
        f1 = factors_by_deg[3][0]
        return ((S6TransitiveSubgroups.C6, False) if has_square_disc(f1)
                else (S6TransitiveSubgroups.D6, False))
    elif L == [3, 3]:
        f1, f2 = factors_by_deg[3]
        any_square = has_square_disc(f1) or has_square_disc(f2)
        return ((S6TransitiveSubgroups.G18, False) if any_square
                else (S6TransitiveSubgroups.G36m, False))
    elif L == [2, 4]:
        if T_has_sq_disc:
            return (S6TransitiveSubgroups.S4p, True)
        f1 = factors_by_deg[4][0]
        return ((S6TransitiveSubgroups.A4xC2, False) if has_square_disc(f1)
                else (S6TransitiveSubgroups.S4xC2, False))
    elif L == [1, 1, 4]:
        return ((S6TransitiveSubgroups.A4, True) if T_has_sq_disc
                else (S6TransitiveSubgroups.S4m, False))
    elif L == [1, 5]:
        return ((S6TransitiveSubgroups.PSL2F5, True) if T_has_sq_disc
                else (S6TransitiveSubgroups.PGL2F5, False))
    elif L == [1, 1, 1, 3]:
        return (S6TransitiveSubgroups.S3, False)
    if L != [6]:
        raise ArithmeticError('Unexpected sextic resolvent factorization')
    history = set()
    for i in range(max_tries):
        R = get_resolvent_by_lookup(T, 2)
        if R.is_sqf:
            break
        _, T = tschirnhausen_transformation(T, max_tries=max_tries,
                                            history=history,
                                            fixed_order=not randomize)
    else:
        raise MaxTriesException
    T_has_sq_disc = has_square_disc(T)
    if R.is_irreducible:
        return ((S6TransitiveSubgroups.A6, True) if T_has_sq_disc
                else (S6TransitiveSubgroups.S6, False))
    return ((S6TransitiveSubgroups.G36p, True) if T_has_sq_disc
            else (S6TransitiveSubgroups.G72, False))


def _poly_galois_group(f, by_name=False, max_tries=30, randomize=False):
    from ... import Poly, QQ, ZZ, sqrt
    from ...combinatorics.galois import (
        S1TransitiveSubgroups as G1, S2TransitiveSubgroups as G2,
        S3TransitiveSubgroups as G3, S4TransitiveSubgroups as G4,
    )
    max_tries = operator.index(max_tries)
    if max_tries < 1:
        raise ValueError('max_tries must be positive')
    # randomize only changes which Tschirnhausen transformations are tried
    # for degrees 5 and 6; the group itself is determined exactly.
    try:
        domain = f.domain
    except NotImplementedError:
        domain = None
    if not f.is_univariate or domain not in (ZZ, QQ) or not f.is_irreducible:
        raise ValueError('Polynomial must be irreducible and univariate over ZZ or QQ.')
    degree = int(f.degree())
    if degree < 1:
        raise ValueError('Constant polynomial has no Galois group.')
    if degree > 6:
        raise ValueError('Only polynomials up to degree 6 are supported.')
    if degree > 4:
        g, _ = f.make_monic_over_integers_by_scaling_roots()
        solver = (_galois_group_degree_5_lookup_ext_factor if degree == 5
                  else _galois_group_degree_6_lookup)
        name, alternating = solver(g, max_tries=max_tries, randomize=randomize)
        return (name if by_name else name.get_perm_group()), alternating
    if degree == 1:
        name, alternating = G1.S1, True
    elif degree == 2:
        name, alternating = G2.S2, False
    else:
        discriminant = f.discriminant()
        alternating = bool(sqrt(discriminant).is_Rational)
        if degree == 3:
            name = G3.A3 if alternating else G3.S3
        else:
            _, a, b, c, d = f.monic().all_coeffs()
            x = f.gens[0]
            resolvent = Poly(x**3 - b*x**2 + (a*c-4*d)*x + 4*b*d-a*a*d-c*c, x, domain=QQ)
            degrees = sorted(int(p.degree()) for p, multiplicity in resolvent.factor_list()[1]
                             for _ in range(multiplicity))
            if degrees == [3]:
                name = G4.A4 if alternating else G4.S4
            elif degrees == [1, 1, 1]:
                name = G4.V
            elif degrees == [1, 2]:
                # Over Q(sqrt(discriminant)), C4 has an intransitive even
                # subgroup C2, whereas D4 has the transitive subgroup V4.
                field = QQ.algebraic_field(sqrt(discriminant))
                factors = f.set_domain(field).factor_list()[1]
                name = G4.C4 if len(factors) > 1 else G4.D4
            else:
                raise ArithmeticError('Unexpected quartic resolvent factorization')
    return (name if by_name else name.get_perm_group()), alternating


def galois_group(f, *gens, by_name=False, max_tries=30, randomize=False, **args):
    """Return the Galois group and whether it lies in the alternating group.

    Irreducible univariate polynomials over ZZ and QQ through degree six are
    supported.
    """
    from ... import Poly
    f = Poly(f, *gens, **args)
    return _poly_galois_group(f, by_name=by_name, max_tries=max_tries, randomize=randomize)
