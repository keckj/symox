class _Object:
    __slots__=('_args',)
    @property
    def args(self):return self._args
    @property
    def func(self):return type(self)
    def __hash__(self):return hash((type(self),self.args))
    def __eq__(self,other):return type(self) is type(other) and self.args==other.args
    def __ne__(self,other):return not self==other
    def __reduce__(self):return type(self),self.args
    def copy(self):return self
    def doit(self,**hints):return self
    @property
    def free_symbols(self):
        from .. import Symbol
        result=set();pending=list(self.args)
        while pending:
            value=pending.pop()
            if isinstance(value,str):result.add(Symbol(value))
            elif isinstance(value,(tuple,list)):pending.extend(value)
            elif hasattr(value,'free_symbols'):result.update(value.free_symbols)
        return result
    def has(self,*patterns):
        pending=[self];seen=set()
        while pending:
            value=pending.pop()
            if isinstance(value,(tuple,list)):pending.extend(value);continue
            if any(isinstance(value,pattern) if isinstance(pattern,type) else value==pattern for pattern in patterns):return True
            if value in seen:continue
            seen.add(value)
            if len(seen)>10000:raise NotImplementedError('Tensor inspection exceeds 10000 nodes')
            pending.extend(getattr(value,'args',()))
        return False
    def sort_key(self,order=None):
        from .. import S
        return (5,0,type(self).__name__),(1,(str(self),)),S.One.sort_key(),S.One
    def xreplace(self,mapping):
        from .._core import Expr
        if self in mapping:return mapping[self]
        def replace(value):
            if isinstance(value,tuple):return tuple(map(replace,value))
            if isinstance(value,Expr):
                scalar_mapping={old:new for old,new in mapping.items() if isinstance(old,(Expr,int,float,str))}
                return value.xreplace(scalar_mapping) if scalar_mapping else value
            return value.xreplace(mapping) if hasattr(value,'xreplace') else mapping.get(value,value)
        return self.func(*(replace(value) for value in self.args))
    def subs(self,*args,**kwargs):
        from collections.abc import Mapping
        pairs=(args[0].items() if len(args)==1 and isinstance(args[0],Mapping)
               else args[0] if len(args)==1 else [args])
        value=self
        for old,new in pairs:value=value.xreplace({old:new})
        return value


class TensorIndexType(_Object):
    __slots__=('_autogenerated','_metric','_delta','_epsilon','_foreign')
    def __new__(cls,name,dummy_name=None,dim=None,eps_dim=None,metric_symmetry=1,metric_name='metric',**kwargs):
        from .. import Symbol,sympify
        if 'dummy_fmt' in kwargs:
            import warnings
            warnings.warn('Use dummy_name instead of dummy_fmt',DeprecationWarning,stacklevel=2)
            dummy_name=kwargs.pop('dummy_fmt')
        if kwargs:raise NotImplementedError('These tensor index-type options are not supported')
        name=str(name)
        if not name:raise ValueError('Tensor type names must not be empty')
        dummy_name=name[0] if dummy_name is None else str(dummy_name)
        if not dummy_name:raise ValueError('Tensor type names must not be empty')
        dim=Symbol('dim_'+dummy_name) if dim is None else sympify(dim)
        eps_dim=dim if eps_dim is None else sympify(eps_dim)
        if dim.is_integer is False or dim.is_negative is True:raise ValueError('Tensor dimensions must be nonnegative integers or symbolic')
        if eps_dim.is_integer is False or eps_dim.is_negative is True:raise ValueError('Epsilon dimensions must be nonnegative integers or symbolic')
        if metric_symmetry not in (None,-1,0,1):raise ValueError('Metric symmetry must be -1, 0, 1 or None')
        result=object.__new__(cls)
        result._args=(name,dummy_name,dim,eps_dim,metric_symmetry,str(metric_name))
        result._autogenerated=0;result._metric=result._delta=result._epsilon=result._foreign=None
        return result
    @property
    def name(self):return self.args[0]
    @property
    def dummy_name(self):return self.args[1]
    @property
    def dim(self):return self.args[2]
    @property
    def eps_dim(self):return self.args[3]
    @property
    def metric(self):
        from ._expressions import TensorHead
        if self.args[4] is None:return None
        if self._metric is None:
            sym=TensorSymmetry.no_symmetry(2) if self.args[4]==0 else TensorSymmetry.fully_symmetric(2*self.args[4])
            self._metric=TensorHead(self.args[5],[self,self],sym)
        return self._metric
    @property
    def delta(self):
        from ._expressions import TensorHead
        if self._delta is None:self._delta=TensorHead('KD',[self,self],TensorSymmetry.fully_symmetric(2))
        return self._delta
    @property
    def epsilon(self):
        from ._expressions import TensorHead
        if not self.eps_dim.is_Integer:return None
        if not 0<=int(self.eps_dim)<=MAX_SLOTS:raise NotImplementedError('Epsilon rank exceeds 32')
        if self._epsilon is None:self._epsilon=TensorHead('Eps',[self]*int(self.eps_dim),TensorSymmetry.fully_symmetric(-int(self.eps_dim)))
        return self._epsilon
    def set_metric(self,tensor):
        if tensor.index_types!=[self,self]:raise ValueError('A metric requires two indices of this type')
        if self.metric is None or tensor.symmetry!=self.metric.symmetry:
            raise ValueError('A replacement metric must preserve the declared slot symmetry')
        self._metric=tensor
        if self._foreign is not None:self._foreign.set_metric(tensor.to_sympy())
    def get_kronecker_delta(self):return self.delta
    def get_epsilon(self):return self.epsilon
    def __lt__(self,other):return (self.name,repr(self.args))<(other.name,repr(other.args))
    def __repr__(self):return self.name
    __str__=__repr__
    def to_sympy(self):
        from sympy.tensor.tensor import TensorIndexType
        if self._foreign is None:
            self._foreign=TensorIndexType(self.name,self.dummy_name,self.dim.to_sympy(),self.eps_dim.to_sympy(),self.args[4],self.args[5])
            if self._metric is not None and self._metric.name!=self.args[5]:
                self._foreign.set_metric(self._metric.to_sympy())
        return self._foreign


class TensorIndex(_Object):
    __slots__=()
    def __new__(cls,name,tensor_index_type,is_up=True):
        if not isinstance(tensor_index_type,TensorIndexType):raise TypeError('An index requires a TensorIndexType')
        if name is True:
            name='_i'+str(tensor_index_type._autogenerated);tensor_index_type._autogenerated+=1
        elif not isinstance(name,str) and not getattr(name,'is_Symbol',False):raise ValueError('An index name must be a string or symbol')
        result=object.__new__(cls);result._args=(str(name),tensor_index_type,bool(is_up));return result
    @property
    def name(self):return self.args[0]
    @property
    def tensor_index_type(self):return self.args[1]
    @property
    def is_up(self):return self.args[2]
    def __neg__(self):return type(self)(self.name,self.tensor_index_type,not self.is_up)
    def __lt__(self,other):return _index_key(self)<_index_key(other)
    def __repr__(self):return ('' if self.is_up else '-')+self.name
    __str__=__repr__
    def matches(self,expr,repl_dict=None,old=False):return dict(repl_dict or {}) if self==expr else None
    def match(self,pattern,old=False):return pattern.matches(self,old=old)
    def to_sympy(self):
        from sympy.tensor.tensor import TensorIndex
        return TensorIndex(self.name,self.tensor_index_type.to_sympy(),self.is_up)


def _index_key(index):return (index.tensor_index_type.name,repr(index.tensor_index_type.args),index.name,not index.is_up)
def _name_key(index):return index.tensor_index_type,index.name


def tensor_indices(s,typ):
    from .. import symbols
    if not isinstance(s,str):raise ValueError('Index names must be a string')
    names=symbols(s,seq=True)
    result=[TensorIndex(name,typ) for name in names]
    return result[0] if len(result)==1 else result


class TensorSymmetry(_Object):
    __slots__=()
    def __new__(cls,*args,**kwargs):
        if kwargs:raise TypeError('Unknown symmetry options')
        if len(args)==1:base,generators=args[0]
        elif len(args)==2:base,generators=args
        else:raise TypeError('Supply a base and signed permutation generators')
        base=tuple(map(operator.index,base));generators=tuple(generators)
        if not generators or any(not isinstance(g,Permutation) for g in generators):raise TypeError('Symmetries require native permutation generators')
        degree=generators[0].size
        if not 2<=degree<=MAX_SLOTS+2 or any(g.size!=degree for g in generators):raise ValueError('Symmetry generator degree is invalid')
        rank=degree-2
        if any(sorted(g.array_form[-2:])!=[rank,rank+1] for g in generators):raise ValueError('The last two permutation points must encode the sign')
        if any(not 0<=value<rank for value in base):raise ValueError('Symmetry base is outside the tensor slots')
        result=object.__new__(cls);result._args=(base,generators);return result
    @property
    def base(self):return self.args[0]
    @property
    def generators(self):return self.args[1]
    @property
    def rank(self):return self.generators[0].size-2
    @classmethod
    def no_symmetry(cls,rank):
        rank=operator.index(rank)
        if not 0<=rank<=MAX_SLOTS:raise ValueError('Tensor rank must lie between 0 and 32')
        return cls((),(Permutation(range(rank+2)),))
    @classmethod
    def fully_symmetric(cls,rank):
        rank=operator.index(rank);size=abs(rank)
        if size>MAX_SLOTS:raise ValueError('Tensor rank exceeds 32')
        generators=[]
        for i in range(size-1):
            images=list(range(size+2));images[i],images[i+1]=images[i+1],images[i]
            if rank<0:images[-2:]=reversed(images[-2:])
            generators.append(Permutation(images))
        return cls(tuple(range(max(0,size-1))),generators or [Permutation(range(size+2))])
    @classmethod
    def direct_product(cls,*args):
        blocks=[operator.index(value) for value in args];size=sum(map(abs,blocks))
        if size>MAX_SLOTS:raise ValueError('Tensor rank exceeds 32')
        base=[];generators=[];offset=0
        for block in blocks:
            group=cls.fully_symmetric(block)
            base.extend(offset+value for value in group.base)
            for generator in group.generators:
                images=list(range(size+2));local=generator.array_form
                for i in range(abs(block)):images[offset+i]=offset+local[i]
                if local[-1]!=len(local)-1:images[-2:]=reversed(images[-2:])
                if images!=list(range(size+2)):generators.append(Permutation(images))
            offset+=abs(block)
        return cls(base,generators or [Permutation(range(size+2))])
    @classmethod
    def riemann(cls):return cls((0,2),[Permutation(p) for p in [(1,0,2,3,5,4),(0,1,3,2,5,4),(2,3,0,1,4,5)]])
    def __repr__(self):return 'TensorSymmetry(%r, %r)' % self.args
    def to_sympy(self):
        from sympy.tensor.tensor import TensorSymmetry
        return TensorSymmetry(self.base,[g.to_sympy() for g in self.generators])


class _IndexStructure:
    def __init__(self,indices):
        self.indices=list(indices);self.index_types=[i.tensor_index_type for i in indices]
        positions={}
        for position,index in enumerate(indices):positions.setdefault(_name_key(index),[]).append(position)
        self.free=[];self.dum=[]
        for group in positions.values():
            if len(group)==1:self.free.append((indices[group[0]],group[0]))
            elif len(group)==2:
                first,second=group
                if indices[first].is_up==indices[second].is_up:raise ValueError('Repeated indices must have opposite variance')
                self.dum.append((first,second) if indices[first].is_up else (second,first))
            else:raise ValueError('An Einstein index may occur at most twice in a product')
        self.free.sort(key=lambda item:_index_key(item[0]));self.dum.sort();self._ext_rank=len(indices)
    def get_indices(self):return list(self.indices)
    def get_free_indices(self):return [index for index,_ in sorted(self.free,key=lambda item:item[1])]
    def indices_canon_args(self):
        n=len(self.indices);images=[None]*n+[n,n+1]
        ordered_free=sorted(self.free,key=lambda item:_index_key(item[0]))
        for i,(_,position) in enumerate(ordered_free):images[position]=i
        dummies=[];symmetries=[];cursor=len(ordered_free);previous=None
        for upper,lower in sorted(self.dum,key=lambda pair:(_index_key(self.indices[pair[0]])[:2],pair[0])):
            typ=self.indices[upper].tensor_index_type
            if typ!=previous:
                dummies.append([]);symmetries.append(0 if typ.args[4]==1 else 1 if typ.args[4]==-1 else None);previous=typ
            images[upper],images[lower]=cursor,cursor+1;dummies[-1].extend((cursor,cursor+1));cursor+=2
        return Permutation(images),dummies,symmetries
    def perm2tensor(self,g,is_canon_bp=False):
        images=g.array_form if isinstance(g,Permutation) else list(g)
        if len(images)!=len(self.indices)+2:raise ValueError('Index permutation has the wrong degree')
        Permutation(images)
        if sorted(images[-2:])!=[len(self.indices),len(self.indices)+1]:raise ValueError('An index permutation must preserve its sign points')
        ordered=[i for i,_ in sorted(self.free,key=lambda item:_index_key(item[0]))]
        for upper,lower in sorted(self.dum,key=lambda pair:(_index_key(self.indices[pair[0]])[:2],pair[0])):ordered.extend((self.indices[upper],self.indices[lower]))
        return _IndexStructure([ordered[position] for position in images[:-2]])
