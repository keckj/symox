"""Portable Slang source and optional SlangPy numerical execution.

Source generation does not import SlangPy. Scalar functions are vectorized by
SlangPy at runtime; their outputs stay on the selected device by default.
"""

from __future__ import annotations

import hashlib
import math
import numbers
import re

from .pytorch import _arguments, _contains_conditionals, _cse_preserving_assumptions, _expressions


_DTYPES = {"float32": "float", "float": "float", "float64": "double", "double": "double"}


def _dtype(dtype):
    try:
        return _DTYPES[dtype]
    except (KeyError, TypeError):
        raise ValueError("Slang dtype must be 'float32' or 'float64'") from None


def _generate(name, args, exprs, dtype, cse, user_functions):
    from symox import Symbol, _core
    from symox.printing.slang import _is_slang_identifier

    if not _is_slang_identifier(name) or name.startswith("_sx_"):
        raise ValueError("Function name must be a Slang identifier outside the reserved '_sx_' namespace")
    scalar_type = _dtype(dtype)
    if not isinstance(cse, bool):
        raise TypeError("cse must be a bool")
    top, symbols, _, _ = _arguments(args, backend="Slang")
    expressions, structure = _expressions(exprs)
    free = set().union(*(expression.free_symbols for expression in expressions)) if expressions else set()
    unknown = free.difference(symbols)
    if unknown:
        raise ValueError("Expression contains unbound symbols: " + ", ".join(sorted(map(str, unknown))))
    if user_functions is not None and not isinstance(user_functions, dict):
        raise TypeError("user_functions must be a dict mapping symbolic names to Slang function names")
    functions = {}
    for key, value in (user_functions or {}).items():
        key = key if isinstance(key, str) else getattr(key, "__name__", None)
        if not isinstance(key, str) or not isinstance(value, str) or not re.fullmatch(r"[A-Za-z_][A-Za-z_0-9]*(?:::[A-Za-z_][A-Za-z_0-9]*)*", value):
            raise ValueError("Custom functions must map names to Slang identifiers or namespace-qualified names")
        functions[key] = value
    dummy_symbols = [Symbol(f"_sx_input_{index}", **symbol.assumptions0) for index, symbol in enumerate(symbols)]
    expressions = [expression.xreplace(dict(zip(symbols, dummy_symbols))) for expression in expressions]
    output_types = ["bool" if _core._slang_type(expression) == "bool" else scalar_type for expression in expressions]
    # Ternaries short-circuit, but hoisting a branch expression into a CSE
    # temporary would defeat that guarantee.
    replacements = []
    if cse and expressions and not _contains_conditionals(expressions):
        replacements, expressions = _cse_preserving_assumptions(expressions, "_sx_cse")
    names = {symbol: f"_sx_v_{index}" for index, symbol in enumerate(dummy_symbols)}
    names.update({symbol: f"_sx_t_{index}" for index, (symbol, _) in enumerate(replacements)})

    temporary_types = {}

    def type_of(expression):
        return temporary_types.get(expression, "bool" if _core._slang_type(expression) == "bool" else scalar_type)

    def emit(expression):
        return _core._slangcode(expression, dtype=dtype, symbol_names=names, user_functions=functions)

    scalar_output = structure[0] == "leaf"
    result_type = output_types[0] if scalar_output else f"_sx_result_{name}"
    lines = ["// Generated by symox. Matrix/array result fields follow row-major leaf order."]
    if not scalar_output:
        lines.append(f"struct {result_type}")
        lines.append("{")
        for index, output_type in enumerate(output_types):
            lines.append(f"    {output_type} _sx_o_{index};")
        if not output_types:
            # Slang does not allow an empty struct. The runtime does not launch
            # empty-output graphs; this field keeps source modules valid.
            lines.append("    uint _sx_empty;")
        lines.append("};")
        lines.append("")
    parameters = ", ".join(f"{scalar_type} {names[symbol]}" for symbol in dummy_symbols)
    lines.extend([f"{result_type} {name}({parameters})", "{"])
    for symbol, expression in replacements:
        temporary_types[symbol] = type_of(expression)
        lines.append(f"    {temporary_types[symbol]} {names[symbol]} = {emit(expression)};")
    rendered = [emit(expression) for expression in expressions]
    if scalar_output:
        lines.append(f"    return {rendered[0]};")
    else:
        lines.append(f"    {result_type} _sx_result;")
        for index, value in enumerate(rendered):
            lines.append(f"    _sx_result._sx_o_{index} = {value};")
        if not rendered:
            lines.append("    _sx_result._sx_empty = 0u;")
        lines.append("    return _sx_result;")
    lines.append("}")
    return "\n".join(lines) + "\n", top, symbols, structure, output_types, scalar_type, result_type


def slangcode_function(name, args, exprs, *, dtype="float32", cse=True, user_functions=None):
    """Return a standalone scalar Slang function with shared common subexpressions.

    Scalar expressions return a scalar. Lists, tuples, matrices and NumPy arrays
    return a generated struct with ``_sx_o_0``, ``_sx_o_1``, ... fields in depth
    first row-major order. Inputs are safely renamed ``_sx_v_0``, ... in declared
    order. No runtime library or GPU is required to generate source.

    Custom functions name existing Slang functions; declare/import those in the
    surrounding module. Float64 availability depends on the compilation target.
    """
    return _generate(name, args, exprs, dtype, cse, user_functions)[0]


def slang_kernel(name, args, exprs, *, dtype="float32", cse=True, user_functions=None, workgroup_size=64):
    """Export a scalar function plus an explicit ``name_kernel`` compute entry.

    The entry takes ``_sx_in_i`` StructuredBuffers, ``_sx_out_i`` writable
    StructuredBuffers and a ``uint _sx_count``. Every input/output buffer has
    ``_sx_count`` scalar elements. Matrices/containers use one output buffer per
    scalar leaf; boolean output buffers use portable uint32 storage (0 or 1).
    Broadcasting and arbitrary strides belong to the host binding;
    :func:`slang_lambdify` supplies them through SlangPy instead.
    """
    if isinstance(workgroup_size, bool) or not isinstance(workgroup_size, int) or not 1 <= workgroup_size <= 1024:
        raise ValueError("workgroup_size must be an integer between 1 and 1024")
    source, _, symbols, structure, output_types, scalar_type, result_type = _generate(
        name, args, exprs, dtype, cse, user_functions
    )
    parameters = [f"    uniform StructuredBuffer<{scalar_type}> _sx_in_{i}" for i in range(len(symbols))]
    parameters += [f"    uniform RWStructuredBuffer<{'uint' if t == 'bool' else t}> _sx_out_{i}" for i, t in enumerate(output_types)]
    parameters += ["    uniform uint _sx_count", "    uint3 _sx_dispatch : SV_DispatchThreadID"]
    lines = [source.rstrip(), "", '[shader("compute")]', f"[numthreads({workgroup_size}, 1, 1)]", f"void {name}_kernel(", ",\n".join(parameters), ")", "{", "    uint _sx_index = _sx_dispatch.x;", "    if (_sx_index >= _sx_count) return;"]
    inputs = ", ".join(f"_sx_in_{i}[_sx_index]" for i in range(len(symbols)))
    lines.append(f"    {result_type} _sx_value = {name}({inputs});")
    for index in range(len(output_types)):
        value = "_sx_value" if structure[0] == "leaf" else f"_sx_value._sx_o_{index}"
        if output_types[index] == "bool":
            value = f"uint({value})"
        lines.append(f"    _sx_out_{index}[_sx_index] = {value};")
    lines.append("}")
    return "\n".join(lines) + "\n"


def slang_lambdify(args, exprs, *, device=None, backend="auto", dtype="float32", cse=True, user_functions=None, return_type="tensor"):
    """Compile a numerical Slang function using the optional ``slangpy`` package.

    Calls accept NumPy arrays, real Python scalars and SlangPy Tensors. Arrays
    broadcast; existing SlangPy Tensors remain resident on their device. Results
    are SlangPy Tensors, with batch dimensions before matrix/array dimensions.
    ``return_type='numpy'`` explicitly copies results to the host. Lists/tuples
    retain their structure. CPU dispatch is not supported by this adapter.

    The callable accepts ``out=`` for reusable SlangPy Tensor outputs and
    ``_append_to=`` for a SlangPy command encoder. Compilation/dispatch errors
    propagate. SlangPy caches compiled call variants; no Torch/JAX is required.
    Float64 execution currently requires CUDA; source export remains unrestricted.
    """
    if return_type not in ("tensor", "numpy"):
        raise ValueError("return_type must be 'tensor' or 'numpy'")
    name = "symox_generated"
    source, top, symbols, structure, output_types, scalar_type, result_type = _generate(
        name, args, exprs, dtype, cse, user_functions
    )
    try:
        import slangpy as spy
    except ImportError as error:
        raise ImportError("Slang execution requires the optional 'slangpy' package; install symox[slang]") from error
    import numpy as np

    if not isinstance(backend, str) or backend not in {"auto", "automatic", "cuda", "vulkan", "d3d12", "metal", "wgpu", "cpu"}:
        raise ValueError("Unknown Slang backend; expected auto, cuda, vulkan, d3d12, metal or wgpu")
    if isinstance(device, str):
        if backend not in ("auto", "automatic", device):
            raise ValueError("device backend conflicts with backend")
        backend, device = device, None
        if backend not in {"auto", "automatic", "cuda", "vulkan", "d3d12", "metal", "wgpu", "cpu"}:
            raise ValueError("Unknown Slang device backend")
    if device is None:
        device = spy.create_device(type=getattr(spy.DeviceType, "automatic" if backend == "auto" else backend))
    elif not isinstance(device, spy.Device):
        raise TypeError("device must be a SlangPy Device or a backend name")
    elif backend not in ("auto", "automatic") and device.info.type != getattr(spy.DeviceType, backend):
        raise ValueError("device backend conflicts with backend")
    if device.info.type == spy.DeviceType.cpu:
        raise NotImplementedError("SlangPy CPU compute dispatch is not supported; use another backend or export Slang source")
    if scalar_type == "double" and device.info.type != spy.DeviceType.cuda:
        raise NotImplementedError("Slang float64 execution currently requires the CUDA backend; other targets can use source export")
    module = spy.Module.load_from_source(device, "symox_" + hashlib.sha256(source.encode()).hexdigest()[:24], source)
    kernel = module.require_function(name)
    numpy_dtype = np.dtype("float64" if scalar_type == "double" else "float32")
    variants = {}
    input_types = {"bool", "half", "float", "double", "int", "uint", "int8_t", "uint8_t", "int16_t", "uint16_t", "int64_t", "uint64_t"}

    def typed_kernel(values):
        types = tuple(value.dtype.name if isinstance(value, spy.Tensor) else scalar_type for value in values)
        if all(item == scalar_type for item in types):
            return kernel
        if types not in variants:
            parameters = ", ".join(f"{item} _sx_a_{index}" for index, item in enumerate(types))
            inputs = ", ".join(f"{scalar_type}(_sx_a_{index})" for index in range(len(types)))
            shim = f"\n{result_type} _sx_invoke({parameters}) {{ return {name}({inputs}); }}\n"
            variant_source = source + shim
            variant = spy.Module.load_from_source(device, "symox_" + hashlib.sha256(variant_source.encode()).hexdigest()[:24], variant_source)
            variants[types] = (variant, variant.require_function("_sx_invoke"))
        return variants[types][1]

    def flatten_inputs(values):
        if len(values) != len(top):
            raise TypeError(f"Expected {len(top)} positional arguments, received {len(values)}")
        flattened = []

        def visit(declared, value):
            if isinstance(declared, (tuple, list)):
                if not isinstance(value, (tuple, list)) or len(value) != len(declared):
                    raise ValueError("Nested Slang function arguments must match the declared list/tuple structure")
                for child, item in zip(declared, value):
                    visit(child, item)
            else:
                flattened.append(value)

        for declared, value in zip(top, values):
            visit(declared, value)
        return flattened

    class _PortableBoolTensor(spy.Tensor):
        # SlangPy 0.43.1 interprets device bool storage as one-byte NumPy bools,
        # even on Vulkan where its reflected scalar stride is four bytes. The
        # GPU tensor already has the correct bool layout; fix only host reads.
        def to_numpy(self):
            width = self.dtype.buffer_layout.stride
            storage = self.storage.to_numpy()
            raw = np.ndarray(
                tuple(self.shape), dtype=np.dtype(f"u{width}"), buffer=storage,
                offset=self.offset * width,
                strides=tuple(stride * width for stride in self.strides),
            )
            return raw != 0

        def view(self, shape, strides=None, offset=0):
            if strides is None:
                tensor = super().view(shape, offset=offset)
            else:
                tensor = super().view(shape, strides, offset)
            return wrap_bool(tensor)

        def __getitem__(self, key):
            return wrap_bool(super().__getitem__(key))

        def broadcast_to(self, shape):
            return wrap_bool(super().broadcast_to(shape))

    def wrap_bool(tensor):
        if tensor.dtype.name == "bool" and tensor.dtype.buffer_layout.stride != 1 and not isinstance(tensor, _PortableBoolTensor):
            return _PortableBoolTensor(tensor.storage, tensor.dtype, tensor.shape, tensor.strides, tensor.offset)
        return tensor

    def allocate(shape, result_dtype):
        # SlangPy's convenience constructor rejects rank zero and zero-sized
        # storage; views over one allocated element support both correctly.
        count = max(math.prod(shape), 1)
        return wrap_bool(spy.Tensor.empty(device, (count,), result_dtype).view(shape))

    def output_container(batch_shape, supplied):
        fields = {}

        def validate(tensor, shape, result_dtype):
            if not isinstance(tensor, spy.Tensor):
                raise TypeError("out leaves must be SlangPy Tensors")
            if tensor.device != device or tuple(tensor.shape) != shape or tensor.dtype.name != result_dtype:
                raise ValueError("out tensor device, shape or dtype does not match generated output")
            return wrap_bool(tensor)

        def visit(node, output=None):
            kind = node[0]
            if kind == "leaf":
                index = node[1]
                tensor = allocate(batch_shape, output_types[index]) if output is None else validate(output, batch_shape, output_types[index])
                fields[f"_sx_o_{index}"] = tensor
                return tensor
            if kind == "dense":
                indices = [child[1] for child in node[2]]
                result_dtype = scalar_type if any(output_types[index] != "bool" for index in indices) else "bool"
                if not indices:
                    result_dtype = scalar_type
                shape = batch_shape + node[1]
                tensor = allocate(shape, result_dtype) if output is None else validate(output, shape, result_dtype)
                for index, coordinates in zip(indices, np.ndindex(node[1])):
                    # Mixed bool/numeric dense outputs require numeric storage;
                    # SlangPy inserts scalar conversion when writing each field.
                    fields[f"_sx_o_{index}"] = tensor[(slice(None),) * len(batch_shape) + coordinates]
                return tensor
            if output is not None and (not isinstance(output, (list, tuple)) or len(output) != len(node[1])):
                raise ValueError("out must match the expression container structure")
            values = [visit(child, None if output is None else output[index]) for index, child in enumerate(node[1])]
            return values if kind == "list" else tuple(values)

        return visit(structure, supplied), fields

    def to_numpy(value):
        if isinstance(value, spy.Tensor):
            return value.to_numpy()
        return type(value)(to_numpy(item) for item in value)

    def function(*values, out=None, _append_to=None):
        flattened = flatten_inputs(values)
        normalized, shapes = [], []
        for value in flattened:
            if isinstance(value, spy.Tensor):
                if value.device != device:
                    raise ValueError("Slang function inputs must use the function's device")
                if value.dtype.name not in input_types:
                    raise TypeError("Slang numerical functions require real scalar tensor dtypes")
                normalized.append(value)
                shapes.append(tuple(value.shape))
            else:
                if not isinstance(value, (numbers.Real, np.ndarray, list, tuple, np.number)):
                    raise TypeError("Slang function inputs must be real scalars, NumPy arrays or SlangPy Tensors")
                array = np.asarray(value)
                if array.dtype.kind not in "biuf":
                    raise TypeError("Slang numerical functions require real numeric inputs")
                array = np.asarray(array, dtype=numpy_dtype)
                normalized.append(array)
                shapes.append(array.shape)
        batch_shape = np.broadcast_shapes(*shapes) if shapes else ()
        result, fields = output_container(batch_shape, out)
        if _append_to is not None and return_type == "numpy":
            raise ValueError("return_type='numpy' cannot be combined with deferred _append_to execution")
        if output_types and 0 not in batch_shape:
            converted = []
            for value in normalized:
                if isinstance(value, spy.Tensor):
                    converted.append(value)
                elif value.ndim == 0:
                    converted.append(value.item())
                else:
                    converted.append(spy.Tensor.from_numpy(device, np.ascontiguousarray(value)))
            kwargs = {"_result": fields["_sx_o_0"] if structure[0] == "leaf" else fields}
            if _append_to is not None:
                kwargs["_append_to"] = _append_to
            typed_kernel(converted)(*converted, **kwargs)
        return to_numpy(result) if return_type == "numpy" else result

    function.__source__ = source
    function.__doc__ = "Generated Slang numerical function. Outputs remain on device unless return_type='numpy'."
    function.device = device
    function.module = module
    function.slang_function = kernel
    return function


__all__ = ["slangcode_function", "slang_kernel", "slang_lambdify"]
